#!/usr/bin/env python3
"""Generate the frontend's API types from the backend's OpenAPI schema.

The Pydantic schemas in ``precursor/backend/schemas`` are the single source of
truth for the shapes the API exchanges. This script turns the app's OpenAPI
document into ``frontend/src/lib/generated/apiTypes.ts`` so the frontend reuses
those shapes instead of re-declaring them by hand (``frontend/src/lib/types.ts``
aliases them).

Response vs request shapes. Pydantic always serializes every field of a
response, so a field with a default is still always present in the JSON the
frontend receives. Schemas reached only from responses therefore make every
property required. Schemas reached only from request bodies keep OpenAPI's
``required`` list (fields with defaults may be omitted). The few schemas used
on both sides get two types: ``Name`` (response shape) and ``NameInput``
(request shape), and request-side references point at ``NameInput``.

Usage::

    uv run python scripts/gen_api_types.py           # (re)write the file
    uv run python scripts/gen_api_types.py --check   # fail if it is stale (CI)
    python3 scripts/gen_api_types.py --schema openapi.json   # from a dump

``make api-types`` runs the first form.
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from collections.abc import Iterable
from pathlib import Path
from typing import Any

REPO_ROOT = Path(__file__).resolve().parents[1]
OUTPUT = REPO_ROOT / "frontend" / "src" / "lib" / "generated" / "apiTypes.ts"

HEADER = """\
// AUTO-GENERATED by scripts/gen_api_types.py from the backend's OpenAPI schema.
// Do not edit by hand: change the Pydantic schema, then run `make api-types`.
// CI fails when this file is out of date."""

Schema = dict[str, Any]
PRIMITIVES = {
    "string": "string",
    "integer": "number",
    "number": "number",
    "boolean": "boolean",
    "null": "null",
}
IDENT = re.compile(r"^[A-Za-z_$][A-Za-z0-9_$]*$")


def load_openapi(schema_path: Path | None) -> Schema:
    if schema_path is not None:
        data: Schema = json.loads(schema_path.read_text())
        return data
    sys.path.insert(0, str(REPO_ROOT))
    from precursor.backend.main import create_app

    return create_app().openapi()


# --- reachability -----------------------------------------------------------


def _refs(node: Any) -> set[str]:
    found: set[str] = set()
    stack = [node]
    while stack:
        item = stack.pop()
        if isinstance(item, dict):
            ref = item.get("$ref")
            if isinstance(ref, str):
                found.add(ref.rsplit("/", 1)[-1])
            stack.extend(item.values())
        elif isinstance(item, list):
            stack.extend(item)
    return found


def _closure(roots: Iterable[str], schemas: dict[str, Schema]) -> set[str]:
    seen: set[str] = set()
    stack = list(roots)
    while stack:
        name = stack.pop()
        if name in seen or name not in schemas:
            continue
        seen.add(name)
        stack.extend(_refs(schemas[name]))
    return seen


def classify(openapi: Schema) -> tuple[set[str], set[str]]:
    """Return (request-side, response-side) schema names, transitively."""
    schemas = openapi.get("components", {}).get("schemas", {})
    request_roots: set[str] = set()
    response_roots: set[str] = set()
    for operations in openapi.get("paths", {}).values():
        for operation in operations.values():
            if not isinstance(operation, dict):
                continue
            request_roots |= _refs(operation.get("requestBody", {}))
            request_roots |= _refs(operation.get("parameters", []))
            response_roots |= _refs(operation.get("responses", {}))
    return _closure(request_roots, schemas), _closure(response_roots, schemas)


# --- rendering --------------------------------------------------------------


class Renderer:
    def __init__(self, dual: set[str]) -> None:
        self.dual = dual

    def ref_name(self, name: str, *, request: bool) -> str:
        return f"{name}Input" if request and name in self.dual else name

    def type_of(self, node: Any, *, request: bool, indent: str = "") -> str:
        if not isinstance(node, dict) or not node:
            return "unknown"
        composite = self._composite(node, request=request, indent=indent)
        if composite is not None:
            return composite
        kind = node.get("type")
        if isinstance(kind, list):
            return " | ".join(self.type_of({**node, "type": k}, request=request) for k in kind)
        if kind in PRIMITIVES:
            return PRIMITIVES[kind]
        if kind == "array":
            return self._array(node, request=request, indent=indent)
        if kind == "object" or "properties" in node:
            return self.object_type(node, request=request, indent=indent)
        return "unknown"

    def _composite(self, node: Schema, *, request: bool, indent: str) -> str | None:
        """$ref, const, enum and anyOf/oneOf/allOf; None for anything else."""
        if "$ref" in node:
            return self.ref_name(node["$ref"].rsplit("/", 1)[-1], request=request)
        if "const" in node:
            return json.dumps(node["const"])
        if "enum" in node:
            return " | ".join(json.dumps(value) for value in node["enum"])
        for key, joiner in (("anyOf", " | "), ("oneOf", " | "), ("allOf", " & ")):
            if key in node:
                parts = _dedupe(self.type_of(n, request=request, indent=indent) for n in node[key])
                return joiner.join(_wrap(p) for p in parts) if len(parts) > 1 else parts[0]
        return None

    def _array(self, node: Schema, *, request: bool, indent: str) -> str:
        if "prefixItems" in node:
            items = (self.type_of(n, request=request, indent=indent) for n in node["prefixItems"])
            return f"[{', '.join(items)}]"
        return f"{_wrap(self.type_of(node.get('items'), request=request, indent=indent))}[]"

    def object_type(self, node: Schema, *, request: bool, indent: str) -> str:
        props: dict[str, Any] = node.get("properties", {})
        extra = node.get("additionalProperties")
        if not props:
            if isinstance(extra, dict) and extra:
                value = self.type_of(extra, request=request, indent=indent)
                return f"Record<string, {value}>"
            return "Record<string, unknown>"
        required = set(node.get("required", [])) if request else set(props)
        inner = indent + "  "
        lines = ["{"]
        for name, prop in props.items():
            lines.extend(_doc(prop, inner))
            key = name if IDENT.match(name) else json.dumps(name)
            optional = "" if name in required else "?"
            value = self.type_of(prop, request=request, indent=inner)
            lines.append(f"{inner}{key}{optional}: {value};")
        if isinstance(extra, dict) and extra:
            value = self.type_of(extra, request=request, indent=inner)
            lines.append(f"{inner}[key: string]: {value} | undefined;")
        lines.append(f"{indent}}}")
        return "\n".join(lines)

    def declaration(self, name: str, node: Schema, *, request: bool) -> str:
        body = self.type_of(node, request=request)
        doc = "\n".join(_doc(node, ""))
        prefix = f"{doc}\n" if doc else ""
        if body.startswith("{"):
            return f"{prefix}export interface {name} {body}"
        return f"{prefix}export type {name} = {body};"


def _dedupe(items: Iterable[str]) -> list[str]:
    return list(dict.fromkeys(items))


def _wrap(type_text: str) -> str:
    """Parenthesize unions/intersections used as an array item or union member."""
    if (" | " in type_text or " & " in type_text) and not type_text.startswith("{"):
        return f"({type_text})"
    return type_text


def _doc(node: Any, indent: str) -> list[str]:
    text = node.get("description") if isinstance(node, dict) else None
    if not text:
        return []
    lines = text.strip().replace("*/", "*\\/").splitlines()
    if len(lines) == 1:
        return [f"{indent}/** {lines[0]} */"]
    return [f"{indent}/**", *(f"{indent} * {line}".rstrip() for line in lines), f"{indent} */"]


def render(openapi: Schema) -> str:
    schemas: dict[str, Schema] = openapi.get("components", {}).get("schemas", {})
    request_side, response_side = classify(openapi)
    dual = request_side & response_side
    renderer = Renderer(dual)
    blocks = [HEADER]
    for name in sorted(schemas):
        node = schemas[name]
        is_request_only = name in request_side and name not in response_side
        blocks.append(renderer.declaration(name, node, request=is_request_only))
        if name in dual:
            blocks.append(renderer.declaration(f"{name}Input", node, request=True))
    return "\n\n".join(blocks) + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--schema", type=Path, help="read OpenAPI JSON instead of the app")
    parser.add_argument("--check", action="store_true", help="fail if the file is stale")
    args = parser.parse_args(argv)

    content = render(load_openapi(args.schema))
    if args.check:
        current = OUTPUT.read_text() if OUTPUT.exists() else ""
        if current != content:
            print(
                f"{OUTPUT.relative_to(REPO_ROOT)} is out of date: run `make api-types`.",
                file=sys.stderr,
            )
            return 1
        print("API types are up to date.")
        return 0
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(content)
    print(f"Wrote {OUTPUT.relative_to(REPO_ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
